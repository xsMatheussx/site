import { BadRequestException, Injectable, InternalServerErrorException, NotFoundException } from '@nestjs/common';
import { createHash, randomUUID } from 'node:crypto';
import { createReadStream, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { S3Client, GetObjectCommand, PutObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

@Injectable()
export class StorageService {
  private readonly provider = (process.env.STORAGE_PROVIDER ?? 'local').toLowerCase();
  private readonly root = process.env.STORAGE_LOCAL_DIR ?? join(process.cwd(), 'storage');
  private readonly maxBytes = Number(process.env.STORAGE_MAX_BYTES ?? 50 * 1024 * 1024);
  private readonly bucket = process.env.STORAGE_S3_BUCKET;
  private readonly s3?: S3Client;

  constructor() {
    if (this.provider === 'local') {
      if (!existsSync(this.root)) mkdirSync(this.root, { recursive: true });
      return;
    }

    if (!['s3', 'r2'].includes(this.provider)) {
      throw new InternalServerErrorException(`STORAGE_PROVIDER inválido: ${this.provider}`);
    }
    if (!this.bucket || !process.env.STORAGE_S3_ACCESS_KEY_ID || !process.env.STORAGE_S3_SECRET_ACCESS_KEY) {
      throw new InternalServerErrorException('Configuração de storage S3/R2 incompleta.');
    }

    this.s3 = new S3Client({
      region: process.env.STORAGE_S3_REGION ?? 'auto',
      endpoint: process.env.STORAGE_S3_ENDPOINT || undefined,
      credentials: {
        accessKeyId: process.env.STORAGE_S3_ACCESS_KEY_ID,
        secretAccessKey: process.env.STORAGE_S3_SECRET_ACCESS_KEY,
      },
    });
  }

  async save(buffer: Buffer, originalName: string, mimeType: string) {
    if (buffer.length > this.maxBytes) throw new BadRequestException('Arquivo excede o limite permitido.');
    const safe = originalName.replace(/[^a-zA-Z0-9._-]/g, '_');
    const key = `${randomUUID()}-${createHash('sha256').update(buffer).digest('hex').slice(0,16)}-${safe}`;

    if (this.provider === 'local') {
      writeFileSync(this.pathFor(key), buffer);
      return { key, fileName: originalName, mimeType, size: buffer.length };
    }

    await this.putObject(key, buffer, mimeType);
    return { key, fileName: originalName, mimeType, size: buffer.length };
  }

  async putObject(key: string, buffer: Buffer, mimeType: string) {
    if (buffer.length > this.maxBytes) throw new BadRequestException('Arquivo excede o limite permitido.');
    if (this.provider === 'local') {
      writeFileSync(this.pathFor(key), buffer);
      return;
    }
    if (!this.s3 || !this.bucket) throw new InternalServerErrorException('Storage não configurado.');
    await this.s3.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: buffer, ContentType: mimeType }));
  }

  pathFor(key: string) {
    this.validateKey(key);
    return join(this.root, key);
  }

  stream(key: string) {
    if (this.provider !== 'local') throw new BadRequestException('Stream local indisponível para storage remoto.');
    const path = this.pathFor(key);
    if (!existsSync(path)) throw new NotFoundException('Arquivo não encontrado.');
    return createReadStream(path);
  }

  readLocal(key: string) {
    if (this.provider !== 'local') throw new BadRequestException('Leitura local indisponível para storage remoto.');
    const path = this.pathFor(key);
    if (!existsSync(path)) throw new NotFoundException('Arquivo não encontrado.');
    return readFileSync(path);
  }

  async createDownloadUrl(key: string, fileName?: string) {
    this.validateKey(key);
    if (this.provider === 'local') return null;
    if (!this.s3 || !this.bucket) throw new InternalServerErrorException('Storage não configurado.');

    const ttl = Math.min(Math.max(Number(process.env.STORAGE_SIGNED_URL_TTL_SECONDS ?? 300), 1), 3600);
    const command = new GetObjectCommand({
      Bucket: this.bucket,
      Key: key,
      ...(fileName ? { ResponseContentDisposition: `attachment; filename="${fileName.replace(/"/g, '')}"` } : {}),
    });
    return getSignedUrl(this.s3, command, { expiresIn: ttl });
  }

  getProvider() { return this.provider; }

  private validateKey(key: string) {
    // Keys are generated by TZ Store and deliberately restricted to one path segment.
    if (!/^[a-zA-Z0-9._-]+$/.test(key)) throw new BadRequestException('Chave inválida.');
  }
}
